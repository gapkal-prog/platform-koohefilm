#!/usr/bin/env bash
#
# اجرای همه‌ی آزمون‌ها.
# استفاده: bash wp/tests/run.sh
#
set -uo pipefail

DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
WP="$( dirname "$DIR" )"
fails=0

#
# باینری PHP. اگر در PATH نبود (مثلاً ویندوز + XAMPP)، با متغیر PHP_BIN
# می‌توان مسیر را داد:  PHP_BIN=/c/xampp/php/php.exe bash wp/tests/run.sh
#
PHP_BIN="${PHP_BIN:-php}"
command -v "$PHP_BIN" >/dev/null 2>&1 || PHP_BIN="/c/xampp/php/php.exe"

echo "=========================================================="
echo "۱) بررسی نحوی PHP"
echo "=========================================================="
out="$( find "$WP/plugins" "$WP/themes" -name '*.php' -print0 | xargs -0 -n1 "$PHP_BIN" -l 2>&1 | grep -v 'No syntax errors' )"
if [ -n "$out" ]; then echo "$out"; fails=$(( fails + 1 )); else
  echo "  ✓ همه‌ی فایل‌های PHP بدون خطا ($( find "$WP/plugins" "$WP/themes" -name '*.php' | wc -l ) فایل)"; fi

echo
echo "=========================================================="
echo "۲) بررسی نحوی JavaScript"
echo "=========================================================="
js_fail=0
for f in $( find "$WP/plugins" "$WP/themes" -name '*.js' -not -path '*/node_modules/*' ); do
  node --check "$f" 2>&1 || { echo "  ✗ $f"; js_fail=1; }
done
if [ "$js_fail" -eq 0 ]; then
  echo "  ✓ همه‌ی فایل‌های JS بدون خطا ($( find "$WP/plugins" "$WP/themes" -name '*.js' -not -path '*/node_modules/*' | wc -l ) فایل)"
else fails=$(( fails + 1 )); fi

echo
echo "=========================================================="
echo "۳) ساخت داده‌های آزمون (fixtures)"
echo "=========================================================="
mkdir -p "$DIR/fixtures"
"$PHP_BIN" "$DIR/bootstrap.php" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۴) آزمون موتور نمایش شرطی و سازنده‌ی کوئری"
echo "=========================================================="
"$PHP_BIN" "$DIR/test-visibility.php" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۵) شبیه‌سازی ویرایشگر بلوک"
echo "=========================================================="
node "$DIR/test-editor.cjs" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۶) آزمون حالت تیره/روشن"
echo "=========================================================="
node "$DIR/test-color-mode.cjs" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۷) آزمون سفارشی‌ساز (سربرگ چسبان و گزینه‌ها)"
echo "=========================================================="
node "$DIR/test-customize.cjs" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۸) آزمون استایل ویرایشگر سایت و ثبت بلوک‌های قالب"
echo "=========================================================="
node "$DIR/test-editor-styles.cjs" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۹) آزمون فهرست همبرگری موبایل"
echo "=========================================================="
node "$DIR/test-mobile-nav.cjs" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۱۰) آزمون آرشیو، دسته‌بندی و نوار فیلتر"
echo "=========================================================="
node "$DIR/test-archive-filter.cjs" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۱۱) آزمون تنوع ظاهری قالب، الگو و بلوک‌ها"
echo "=========================================================="
node "$DIR/test-variants.cjs" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۱۲) آزمون ریسپانسیو، دسترس‌پذیری و گزینشگرهای یتیم"
echo "=========================================================="
node "$DIR/test-responsive.cjs" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۱۳) آزمون بومِ ویرایشگر بلوک‌های افزونه"
echo "=========================================================="
node "$DIR/test-editor-canvas.cjs" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
if [ "$fails" -eq 0 ]; then echo "نتیجه: همه‌ی آزمون‌ها موفق ✓"; else echo "نتیجه: $fails بخش با خطا ✗"; fi
echo "=========================================================="
exit "$fails"
