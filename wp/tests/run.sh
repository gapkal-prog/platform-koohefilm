#!/usr/bin/env bash
#
# اجرای همه‌ی آزمون‌ها.
# استفاده: bash wp/tests/run.sh
#
set -uo pipefail

DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
WP="$( dirname "$DIR" )"
fails=0

#
# باینری PHP. اگر در PATH نبود (مثلاً ویندوز + XAMPP)، با متغیر PHP_BIN
# می‌توان مسیر را داد:  PHP_BIN=/c/xampp/php/php.exe bash wp/tests/run.sh
#
PHP_BIN="${PHP_BIN:-php}"
command -v "$PHP_BIN" >/dev/null 2>&1 || PHP_BIN="/c/xampp/php/php.exe"

# باینری Node برای سوئیت‌های جاوااسکریپتی.
NODE_BIN="${NODE_BIN:-node}"

echo "=========================================================="
echo "۱) بررسی نحوی PHP"
echo "=========================================================="
out="$( find "$WP/plugins" "$WP/themes" -name '*.php' -print0 | xargs -0 -n1 "$PHP_BIN" -l 2>&1 | grep -v 'No syntax errors' )"
if [ -n "$out" ]; then echo "$out"; fails=$(( fails + 1 )); else
  echo "  ✓ همه‌ی فایل‌های PHP بدون خطا ($( find "$WP/plugins" "$WP/themes" -name '*.php' | wc -l ) فایل)"; fi

echo
echo "=========================================================="
echo "۲) بررسی نحوی JavaScript"
echo "=========================================================="
js_fail=0
for f in $( find "$WP/plugins" "$WP/themes" -name '*.js' -not -path '*/node_modules/*' ); do
  "$NODE_BIN" --check "$f" 2>&1 || { echo "  ✗ $f"; js_fail=1; }
done
if [ "$js_fail" -eq 0 ]; then
  echo "  ✓ همه‌ی فایل‌های JS بدون خطا ($( find "$WP/plugins" "$WP/themes" -name '*.js' -not -path '*/node_modules/*' | wc -l ) فایل)"
else fails=$(( fails + 1 )); fi

echo
echo "=========================================================="
echo "۳) ساخت داده‌های آزمون (fixtures)"
echo "=========================================================="
mkdir -p "$DIR/fixtures"
"$PHP_BIN" "$DIR/bootstrap.php" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۴) آزمون موتور نمایش شرطی و سازنده‌ی کوئری"
echo "=========================================================="
"$PHP_BIN" "$DIR/test-visibility.php" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۵) آزمون تاریخ شمسی و رقم‌های فارسی"
echo "=========================================================="
"$PHP_BIN" "$DIR/test-dates.php" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۶) آزمون باکس دانلود و صفحه‌ی پخش"
echo "=========================================================="
"$PHP_BIN" "$DIR/test-download-watch.php" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۶ب) آزمون عوامل (Crew): تجزیه، پیوند، جست‌وجو"
echo "=========================================================="
"$PHP_BIN" "$DIR/test-crew.php" || fails=$(( fails + 1 ))


echo
echo "=========================================================="
echo "۷ب) آزمون رندر تب‌های صفحه‌ی تنظیمات"
echo "=========================================================="
"$PHP_BIN" "$DIR/test-settings-panel.php" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۸) شبیه‌سازی ویرایشگر بلوک"
echo "=========================================================="
"$NODE_BIN" "$DIR/test-editor.cjs" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۹) آزمون حالت تیره/روشن"
echo "=========================================================="
"$NODE_BIN" "$DIR/test-color-mode.cjs" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۱۰) آزمون سفارشی‌ساز (سربرگ چسبان و گزینه‌ها)"
echo "=========================================================="
"$NODE_BIN" "$DIR/test-customize.cjs" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۱۱) آزمون استایل ویرایشگر سایت و ثبت بلوک‌های قالب"
echo "=========================================================="
"$NODE_BIN" "$DIR/test-editor-styles.cjs" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۱۲) آزمون فهرست همبرگری موبایل"
echo "=========================================================="
"$NODE_BIN" "$DIR/test-mobile-nav.cjs" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۱۳) آزمون آرشیو، دسته‌بندی و نوار فیلتر"
echo "=========================================================="
"$NODE_BIN" "$DIR/test-archive-filter.cjs" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۱۴) آزمون تنوع ظاهری قالب، الگو و بلوک‌ها"
echo "=========================================================="
"$NODE_BIN" "$DIR/test-variants.cjs" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۱۵) آزمون ریسپانسیو، دسترس‌پذیری و گزینشگرهای یتیم"
echo "=========================================================="
"$NODE_BIN" "$DIR/test-responsive.cjs" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۱۶) آزمون پخش‌کننده‌ی حرفه‌ای (HLS، سرعت، قسمت بعدی)"
echo "=========================================================="
"$NODE_BIN" "$DIR/test-player-pro.cjs" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۱۷) آزمون گزارش خرابی لینک و ارتقای پایگاه‌داده"
echo "=========================================================="
"$PHP_BIN" "$DIR/test-reports.php" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۱۸) آزمون درخواست کاربران و پنل «درخواست‌های من»"
echo "=========================================================="
"$PHP_BIN" "$DIR/test-community.php" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۱۹) آزمون داشبورد تحلیلی مدیر"
echo "=========================================================="
"$PHP_BIN" "$DIR/test-analytics.php" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۲۰) آزمون بومِ ویرایشگر بلوک‌های افزونه"
echo "=========================================================="
"$NODE_BIN" "$DIR/test-editor-canvas.cjs" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۲۱) آزمون پشتیبان‌گیری، محتوای نمایشی و WP-CLI"
echo "=========================================================="
"$PHP_BIN" "$DIR/test-portability.php" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۲۲) آزمون دانلود امضاشده و شمارش سرورسوی دانلود"
echo "=========================================================="
"$PHP_BIN" "$DIR/test-downloads.php" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۲۳) آزمون مدیریت لینک‌ها از فهرست پیشخوان"
echo "=========================================================="
"$PHP_BIN" "$DIR/test-links-admin.php" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۲۴) آزمون ابزارهای گروهی نگه‌داشت لینک‌ها"
echo "=========================================================="
"$PHP_BIN" "$DIR/test-link-tools.php" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۲۵) آزمون موتور جستجو (نرمال‌سازی فارسی و شکل‌های جایگزین)"
echo "=========================================================="
"$PHP_BIN" "$DIR/test-search.php" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۲۶) آزمون سلامت ظاهر پیشخوان (CSS در برابر کد)"
echo "=========================================================="
"$NODE_BIN" "$DIR/test-admin-ui.cjs" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۲۷) آزمون به‌روزرسانی افزونه از سرور فروش"
echo "=========================================================="
"$PHP_BIN" "$DIR/test-updater.php" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
echo "۲۸) آزمون مجموعه و کانال (فهرست مرتب، ترتیب خودکار، انتخابگر آثار)"
echo "=========================================================="
"$PHP_BIN" "$DIR/test-collections-channels.php" || fails=$(( fails + 1 ))

echo
echo "=========================================================="
if [ "$fails" -eq 0 ]; then echo "نتیجه: همه‌ی آزمون‌ها موفق ✓"; else echo "نتیجه: $fails بخش با خطا ✗"; fi
echo "=========================================================="
exit "$fails"
